export function pwaLocale(locale) {
  return typeof locale === 'string' && Object.hasOwn(pwaMessages, locale) ? locale : 'en';
}

export function pwaText(t, key, locale = t?.locale) {
  const language = pwaLocale(locale);
  const translated = typeof t === 'function' ? t(key) : key;
  if (typeof translated === 'string' && translated !== key) return translated;
  const dictionary = pwaMessages[language];
  return Object.hasOwn(dictionary, key) ? dictionary[key] : key;
}
